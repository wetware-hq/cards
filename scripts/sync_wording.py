#!/usr/bin/env python3
"""Copy the signed cards wording into WORDING.md (id + line only), plus the reused signed rows named in REUSED,
with the SHA-256 of that content in the header. Run locally when a signed file changes:

    python3 scripts/sync_wording.py CARDS_SIGNED.md REUSED_SIGNED.md

The row count and id set come from the cards signed file itself (no hard-coded count). Fails (exit 1) BEFORE any
hash is computed if any id row in that file cannot be parsed as a final signed row (wrong shape, or marked
draft/pending), if an id repeats, if the copy would not hold exactly the file's ids, or if a reused id is missing. The repo never reads the signed files itself."""
import hashlib, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROW = re.compile(r"^\| ([A-Z]{2,4}-[A-Z0-9-]+) \| [a-z]+ \| ([^|]*?) \|$", re.M)
ROW2 = re.compile(r"^\| ([A-Z]{2,4}-[A-Z0-9-]+) \| ([^|]*?) \|$", re.M)
HEAD = "# Signed wording (generated by scripts/sync_wording.py from the signed tables; do not edit)"
ID_ROW = re.compile(r"^\| ([A-Z]{2,4}-[A-Z0-9-]+) \|.*$", re.M)          # any row that starts with a line id
NOT_FINAL = re.compile(r"\b(DRAFT|PENDING|TBD|TODO)\b|\?\?")
REUSED = ("RF-REVOKED", "ST-UNCONFIRMED", "ST-CONFIRMED", "ST-CHANGED", "ST-DECLINED", "REL-PARENT-PT", "REL-PARENT-CLIN",
          "REL-GUARDIAN-PT", "REL-GUARDIAN-CLIN", "REL-SDM-PT", "REL-SDM-CLIN", "PV-SAMEDAY", "PV-BEFORE-PROC", "PV-ANS-AGENT", "PV-ANS-SDM",
          "PV-DECLINED", "PV-REVOKE", "CQ-SAMEDAY-ALERT", "CQ-BEFORE-PROC", "ST-FLAGGED",
          "RF-NOT-YOURS", "PV-CHECK-PENDING", "PV-TRY-AGAIN", "RUN-TRACES-NOT-RUN", "RF-RESULT-HELD", "CQ-RESULT-TO-DISCUSS", "RF-GRANT-ENDED")


class Mismatch(Exception):
    pass


def signed_ids(cards):
    return [m.group(1) for m in ID_ROW.finditer(cards)]


def rows(cards, reused):
    """Validate first; raises Mismatch before anything is hashed."""
    want = signed_ids(cards)
    found = ROW.findall(cards)
    if len(set(want)) != len(want):
        raise Mismatch(f"duplicate ids in the signed file: {sorted({k for k in want if want.count(k) > 1})}")
    bad = sorted(set(want) - {k for k, _ in found})
    if bad:
        raise Mismatch(f"rows not in final signed form: {bad}")
    draft = sorted(k for k, v in found if NOT_FINAL.search(v))
    if draft:
        raise Mismatch(f"rows marked not final: {draft}")
    if [k for k, _ in found] != want:
        raise Mismatch(f"copy has {len(found)} rows, signed file has {len(want)}")
    other = dict(ROW2.findall(reused))
    gone = [k for k in REUSED if k not in other]
    if gone:
        raise Mismatch(f"reused ids missing: {gone}")
    return found + [(k, other[k]) for k in REUSED]


def render(cards, reused):
    r = rows(cards, reused)
    body = "\n".join(["| id | line |", "|---|---|"] + [f"| {k} | {v} |" for k, v in r]) + "\n"
    return f"{HEAD}\nsha256: {hashlib.sha256(body.encode()).hexdigest()}\n\n{body}"


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        text = render(pathlib.Path(argv[1]).read_text(), pathlib.Path(argv[2]).read_text())
    except Mismatch as e:
        print(f"sync_wording: {e}", file=sys.stderr)
        return 1
    (ROOT / "WORDING.md").write_text(text)
    print(f"WORDING.md: {len(signed_ids(pathlib.Path(argv[1]).read_text()))} signed lines, {len(REUSED)} reused")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
