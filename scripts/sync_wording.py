#!/usr/bin/env python3
"""Copy the signed cards wording into WORDING.md (id + line only), plus the reused signed rows named in REUSED,
with the SHA-256 of that content in the header. Run locally when a signed file changes:

    python3 scripts/sync_wording.py CARDS_SIGNED.md REUSED_SIGNED.md

Fails (exit 1) BEFORE any hash is computed if the cards file does not hold exactly SIGNED_COUNT unique ids
equal to SIGNED_IDS, or if a reused id is missing. The repo never reads the signed files itself."""
import hashlib, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROW = re.compile(r"^\| ([A-Z]{2,4}-[A-Z0-9-]+) \| [a-z]+ \| ([^|]*?) \|$", re.M)
ROW2 = re.compile(r"^\| ([A-Z]{2,4}-[A-Z0-9-]+) \| ([^|]*?) \|$", re.M)
HEAD = "# Signed wording (generated by scripts/sync_wording.py from the signed tables; do not edit)"
SIGNED_COUNT = 49
SIGNED_IDS = frozenset("""
FD-ALLERGIES-PT FD-ALLERGIES-CLIN FD-MEDICINES-PT FD-MEDICINES-CLIN FD-PROBLEMS-PT FD-PROBLEMS-CLIN
FD-PREFERENCES-PT FD-PREFERENCES-CLIN FD-ACTS-FOR-PT FD-ACTS-FOR-CLIN FD-DISCIPLINE-PT FD-DISCIPLINE-CLIN
FD-REGISTRATION-PT FD-REGISTRATION-CLIN FD-TEAM-PT FD-TEAM-CLIN SRC-PATIENT-PT SRC-PATIENT-CLIN SRC-CLINICIAN-PT
SRC-CLINICIAN-CLIN SRC-ONBEHALF-PT SRC-ONBEHALF-CLIN VAL-UNKNOWN-PT VAL-UNKNOWN-CLIN VAL-NONE-ALLERGY-PT
VAL-NONE-ALLERGY-CLIN VAL-NONE-MEDICINES-PT VAL-NONE-MEDICINES-CLIN VAL-NONE-PROBLEMS-PT VAL-NONE-PROBLEMS-CLIN
FL-WRONG-ACTION-PT FL-WRONG-DONE-PT FL-WRONG-MARK-PT FL-WRONG-MARK-CLIN-PT CQ-FACT-FLAGGED PV-FACT-OLD
CQ-FACT-STALE PV-FACT-HIDDEN CQ-FACT-HIDDEN RF-SIGN-APPROVE RF-SIGN-ROUTE RF-SIGN-CLOSE RF-SIGN-LETTER
RF-REG-UNVERIFIED RF-FREE-TEXT RF-ONE-PROFILE RF-SOURCE-UPGRADE RF-SESSION-ENDED PV-DRAFT-NOT-SENT""".split())
REUSED = ("RF-REVOKED", "ST-UNCONFIRMED", "ST-CONFIRMED", "ST-CHANGED", "ST-DECLINED", "REL-PARENT-PT", "REL-PARENT-CLIN",
          "REL-GUARDIAN-PT", "REL-GUARDIAN-CLIN", "REL-SDM-PT", "REL-SDM-CLIN", "PV-SAMEDAY", "PV-BEFORE-PROC", "PV-REVOKE-LIST")


class Mismatch(Exception):
    pass


def rows(cards, reused):
    """Validate first; raises Mismatch before anything is hashed."""
    found = ROW.findall(cards)
    ids = [k for k, _ in found]
    if len(ids) != SIGNED_COUNT or len(set(ids)) != len(ids):
        raise Mismatch(f"row count {len(ids)} ({len(set(ids))} unique), expected {SIGNED_COUNT}")
    if set(ids) != SIGNED_IDS:
        raise Mismatch(f"id set differs: extra {sorted(set(ids) - SIGNED_IDS)} missing {sorted(SIGNED_IDS - set(ids))}")
    other = dict(ROW2.findall(reused))
    gone = [k for k in REUSED if k not in other]
    if gone:
        raise Mismatch(f"reused ids missing: {gone}")
    return found + [(k, other[k]) for k in REUSED]


def render(cards, reused):
    r = rows(cards, reused)
    body = "\n".join(["| id | line |", "|---|---|"] + [f"| {k} | {v} |" for k, v in r]) + "\n"
    return f"{HEAD}\nsha256: {hashlib.sha256(body.encode()).hexdigest()}\n\n{body}"


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        text = render(pathlib.Path(argv[1]).read_text(), pathlib.Path(argv[2]).read_text())
    except Mismatch as e:
        print(f"sync_wording: {e}", file=sys.stderr)
        return 1
    (ROOT / "WORDING.md").write_text(text)
    print(f"WORDING.md: {SIGNED_COUNT} signed lines, {len(REUSED)} reused")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
